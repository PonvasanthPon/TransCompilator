#!/usr/bin/env python3
"""Harvest CU Boulder VerbNet 3.4 XML into a static C frame table.

Pure Python 3 standard library only.  For every verb member of every class
(and nested subclass) we record the real (verb, preposition) -> thematic-role
bindings found in the class's SYNTAX frames, together with the VerbNet class id.
"""
from __future__ import annotations

import re
import sys
import xml.etree.ElementTree as ET
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
RAW = ROOT / "goldmines" / "raw" / "verbnet"
OUT = ROOT / "generated" / "tc_verbnet_frames.h"
LOG = ROOT / "logs" / "goldmine_harvest.log"

ROLE_MAP = {
    "Source": "VN_ROLE_SOURCE",
    "Initial_Location": "VN_ROLE_SOURCE",
    "Initial_State": "VN_ROLE_SOURCE",
    "Destination": "VN_ROLE_DEST",
    "Goal": "VN_ROLE_DEST",
    "Recipient": "VN_ROLE_DEST",
    "Result": "VN_ROLE_DEST",
    "Extent": "VN_ROLE_EXTENT",
    "Asset": "VN_ROLE_EXTENT",
    "Value": "VN_ROLE_EXTENT",
    "Instrument": "VN_ROLE_EXTENT",
    "Co-Theme": "VN_ROLE_CO_THEME",
    "Co-Patient": "VN_ROLE_CO_THEME",
    "Co-Agent": "VN_ROLE_CO_THEME",
    "Theme2": "VN_ROLE_CO_THEME",
}


def scan_class(elem, inherited_members, inherited_class, frames, classes):
    """Walk VNCLASS/VNSUBCLASS, inheriting members and class ids."""
    cls = elem.get("ID") or inherited_class or "unknown"
    classes.add(cls)
    members = list(inherited_members)
    members_el = elem.find("MEMBERS")
    if members_el is not None:
        for m in members_el.findall("MEMBER"):
            name = (m.get("name") or "").strip().lower()
            if name and re.fullmatch(r"[a-z][a-z_-]*", name):
                members.append(name.replace("_", " "))
    frames_el = elem.find("FRAMES")
    if frames_el is not None:
        for frame in frames_el.findall("FRAME"):
            syn = frame.find("SYNTAX")
            if syn is None:
                continue
            children = list(syn)
            for i, child in enumerate(children):
                if child.tag != "PREP":
                    continue
                prep_values = (child.get("value") or "").split()
                # The first NP after the PREP carries the thematic role.
                role = None
                for nxt in children[i + 1:]:
                    if nxt.tag in ("NP", "ADJP", "SELRESTRS"):
                        if nxt.tag in ("NP", "ADJP"):
                            role = ROLE_MAP.get(nxt.get("value") or "")
                            break
                    elif nxt.tag not in ("SELRESTRS",):
                        break
                if not role:
                    continue
                for prep in prep_values:
                    prep = prep.strip().lower().lstrip("?")
                    if prep:
                        for verb in members:
                            frames[(verb, prep, cls)] = role
    for sub in elem.findall("SUBCLASSES"):
        for child in sub.findall("VNSUBCLASS"):
            scan_class(child, members, cls, frames, classes)


def main() -> int:
    base = RAW / "verbnet3.4"
    if not base.is_dir():
        sys.exit(f"missing {base}")
    files = sorted(base.glob("*.xml"))
    frames: dict[tuple[str, str, str], str] = {}
    classes: set[str] = set()
    parse_errors = 0
    verb_members: set[str] = set()
    for path in files:
        try:
            root = ET.parse(path).getroot()
        except ET.ParseError:
            parse_errors += 1
            continue
        scan_class(root, [], None, frames, classes)
        for m in root.findall("./MEMBERS/MEMBER"):
            name = (m.get("name") or "").strip().lower().replace("_", " ")
            if name:
                verb_members.add(name)

    # Deduplicate by (verb, prep); keep the lexicographically first class id
    # so the table has a deterministic, binary-searchable shape.
    dedup: dict[tuple[str, str], tuple[str, str]] = {}
    for (verb, prep, cls), role in sorted(frames.items()):
        key = (verb, prep)
        if key not in dedup:
            dedup[key] = (role, cls)

    entries = sorted(((v, p, role, cls) for (v, p), (role, cls) in dedup.items()),
                     key=lambda x: (x[0], x[1]))

    OUT.parent.mkdir(parents=True, exist_ok=True)
    LOG.parent.mkdir(parents=True, exist_ok=True)
    with OUT.open("w", encoding="utf-8") as fh:
        fh.write("/* AUTO-GENERATED by goldmines/tools/harvest_verbnet.py - DO NOT EDIT BY HAND */\n")
        fh.write("/* Source: CU Boulder VerbNet 3.4 (github.com/cu-clear/verbnet), "
                 "commit ae8e9cfdc2c0d3414b748763612f1a0a34194cc1 */\n")
        fh.write(f"/* {len(files)} XML class files -> {len(entries)} (verb,prep) roles */\n")
        fh.write("#ifndef TC_VERBNET_FRAMES_H\n#define TC_VERBNET_FRAMES_H\n\n")
        fh.write('#include "tc_goldmine.h"\n\n')
        fh.write("static const TCVerbNetFrame TC_VERBNET_FRAMES[] = {\n")
        for verb, prep, role, cls in entries:
            fh.write(f'    {{ "{verb}", "{cls}", "{prep}", {role} }},\n')
        fh.write("};\n")
        fh.write("static const size_t TC_VERBNET_FRAMES_COUNT =\n")
        fh.write("    sizeof(TC_VERBNET_FRAMES) / sizeof(TC_VERBNET_FRAMES[0]);\n\n")
        fh.write("#endif\n")

    with LOG.open("a", encoding="utf-8") as fh:
        fh.write("\n=== CU Boulder VerbNet 3.4 harvest ===\n")
        fh.write("source: goldmines/raw/verbnet/verbnet3.4\n")
        fh.write("commit: ae8e9cfdc2c0d3414b748763612f1a0a34194cc1\n")
        fh.write(f"xml class files parsed: {len(files)} (errors: {parse_errors})\n")
        fh.write(f"classes/subclasses seen: {len(classes)}\n")
        fh.write(f"distinct verb members: {len(verb_members)}\n")
        fh.write(f"(verb, prep) frames emitted: {len(entries)}\n")
        fh.write("sample frames:\n")
        for word in ["deduct", "diminish", "increase", "decrease", "remove",
                     "mix", "show", "reveal", "report", "display", "give"]:
            hits = [e for e in entries if e[0] == word][:4]
            for v, p, role, cls in hits:
                fh.write(f"  {v} + {p} -> {role} [{cls}]\n")
    print(f"harvested {len(entries)} VerbNet frames from {len(files)} classes")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
